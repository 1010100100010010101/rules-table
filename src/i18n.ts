export type Lang = "zh-Hant" | "zh-Hans" | "en";
export const LANGS: Lang[] = ["zh-Hant", "zh-Hans", "en"];

export function normLang(x: unknown): Lang {
  return LANGS.includes(x as Lang) ? (x as Lang) : "zh-Hant";
}

