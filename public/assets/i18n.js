export function fmt(str, vars) {
  return String(str).replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] != null ? vars[k] : m));
}

function systemLang() {
  const l = String(navigator.language || "").toLowerCase();
  if (l === "zh-cn" || l === "zh-sg" || l === "zh-hans" || l === "zh") return "zh-Hans";
  if (l.startsWith("zh")) return "zh-Hant";
  return "en";
}

export function getLang() {
  let l = null;
  try { l = JSON.parse(localStorage.getItem("lang") || "null"); } catch {}
  return LANGS.includes(l) ? l : systemLang();
}

export function setLang(l) {
  if (!LANGS.includes(l)) return;
  try { localStorage.setItem("lang", JSON.stringify(l)); } catch {}
}

export function dict(lang) {
  return DICTS[LANGS.includes(lang) ? lang : getLang()];
}

const HTML_LANG = { "zh-Hant": "zh-Hant", "zh-Hans": "zh-Hans", en: "en" };

// 把 data-i18n / data-i18n-ph 套上文字
export function applyI18n(t, root = document) {
  document.documentElement.lang = HTML_LANG[getLang()] || "zh-Hant";
  for (const e of root.querySelectorAll("[data-i18n]")) {
    const v = e.dataset.i18n.split(".").reduce((o, k) => (o ? o[k] : undefined), t);
    if (v != null) e.textContent = v;
  }
  for (const e of root.querySelectorAll("[data-i18n-ph]")) {
    const v = t[e.dataset.i18nPh];
    if (v != null) e.placeholder = v;
  }
}

// 語言切換按鈕：放進 container，按下後呼叫 onChange(lang)
export function langSwitch(container, onChange) {
  container.replaceChildren();
  const cur = getLang();
  for (const o of LANG_OPTIONS) {
    const b = document.createElement("button");
    b.type = "button";
    b.textContent = o.label;
    b.className = o.v === cur ? "on" : "";
    b.onclick = () => {
      setLang(o.v);
      for (const x of container.children) x.className = x === b ? "on" : "";
      onChange(o.v);
    };
    container.append(b);
  }
}

// 猜規則書是什麼語言，用來決定要不要預設翻譯
const HANS_ONLY = '这们个来时说过还会对开发学门见长问间关没给让认东车书买卖头样话应该进动现实与从经图钱张场边点热标准选择规则须轮掷骰负胜数轮赢输张颗处时当后发';
const HANT_ONLY = '這們個來時說過還會對開發學門見長問間關沒給讓認東車書買賣頭樣話應該進動現實與從經圖錢張場邊點熱標準選擇規則須輪擲骰負勝數輪贏輸張顆處時當後發';
export function detectLang(text) {
  const s = String(text || '');
  let cjk = 0, latin = 0, kana = 0, hangul = 0, hans = 0, hant = 0;
  for (const ch of s) {
    const c = ch.charCodeAt(0);
    if (c >= 0x3040 && c <= 0x30ff) kana++;
    else if (c >= 0xac00 && c <= 0xd7af) hangul++;
    else if (c >= 0x4e00 && c <= 0x9fff) {
      cjk++;
      if (HANS_ONLY.indexOf(ch) >= 0) hans++;
      else if (HANT_ONLY.indexOf(ch) >= 0) hant++;
    } else if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122)) latin++;
  }
  const total = cjk + latin + kana + hangul;
  if (total < 20) return null; // 太短，不判斷
  if (kana > total * 0.05) return 'ja';
  if (hangul > total * 0.1) return 'ko';
  if (latin > cjk * 2) return 'en';
  if (hans > hant) return 'zh-Hans';
  if (hant > hans) return 'zh-Hant';
  return null; // 分不出繁簡就不提示
}

